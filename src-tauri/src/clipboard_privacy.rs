//! Read retention markers before payloads, then validate the clipboard generation again.

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Snapshot {
    pub generation: u64,
    pub marked: bool,
}

impl Snapshot {
    pub fn unchanged_and_public(self, after: Self) -> bool {
        !self.marked && !after.marked && self.generation == after.generation
    }
}

#[cfg(any(target_os = "windows", test))]
fn history_flag(value: u32) -> Result<bool, ()> {
    match value {
        0 => Ok(true),
        1 => Ok(false),
        _ => Err(()),
    }
}

#[cfg(target_os = "macos")]
mod platform {
    use super::Snapshot;
    use objc::{class, msg_send, runtime::Object, sel, sel_impl};
    use std::ffi::CString;

    pub struct Inspector;

    impl Inspector {
        pub fn new() -> Result<Self, ()> {
            Ok(Self)
        }

        pub fn snapshot(&mut self) -> Result<Snapshot, ()> {
            unsafe {
                let pool: *mut Object = msg_send![class!(NSAutoreleasePool), new];
                let pasteboard: *mut Object = msg_send![class!(NSPasteboard), generalPasteboard];
                let result = inspect(pasteboard);
                let _: () = msg_send![pool, drain];
                result
            }
        }
    }

    unsafe fn inspect(pasteboard: *mut Object) -> Result<Snapshot, ()> {
        if pasteboard.is_null() {
            return Err(());
        }
        let before: isize = msg_send![pasteboard, changeCount];
        let types: *mut Object = msg_send![pasteboard, types];
        let mut marked = false;
        for marker in [
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType",
            "com.agilebits.onepassword",
            "net.antelle.keeweb",
            "de.petermaurer.TransientPasteboardType",
            "com.typeit4me.clipping",
            "Pasteboard generator type",
        ] {
            let name = CString::new(marker).unwrap();
            let string: *mut Object =
                msg_send![class!(NSString), stringWithUTF8String: name.as_ptr()];
            if !types.is_null() {
                let contains: bool = msg_send![types, containsObject: string];
                marked |= contains;
            }
        }
        let after: isize = msg_send![pasteboard, changeCount];
        if before != after {
            return Err(());
        }
        Ok(Snapshot {
            generation: before as u64,
            marked,
        })
    }

    #[cfg(test)]
    mod tests {
        use super::*;

        #[test]
        fn reads_markers_on_a_private_pasteboard_without_touching_system_clipboard() {
            unsafe {
                let pool: *mut Object = msg_send![class!(NSAutoreleasePool), new];
                let board: *mut Object = msg_send![class!(NSPasteboard), pasteboardWithUniqueName];
                let initial = inspect(board).unwrap();
                for marker in [
                    "org.nspasteboard.ConcealedType",
                    "org.nspasteboard.TransientType",
                    "com.agilebits.onepassword",
                ] {
                    let _: isize = msg_send![board, clearContents];
                    let name = CString::new(marker).unwrap();
                    let kind: *mut Object =
                        msg_send![class!(NSString), stringWithUTF8String: name.as_ptr()];
                    let empty: *mut Object = msg_send![class!(NSString), string];
                    let _: bool = msg_send![board, setString: empty forType: kind];
                    let snapshot = inspect(board).unwrap();
                    assert!(snapshot.marked);
                    assert!(!initial.unchanged_and_public(snapshot));
                }
                let _: () = msg_send![board, releaseGlobally];
                let _: () = msg_send![pool, drain];
            }
        }
    }
}

#[cfg(target_os = "windows")]
mod platform {
    use super::Snapshot;
    use windows::{
        core::PCWSTR,
        Win32::System::{
            DataExchange::{
                CloseClipboard, GetClipboardData, GetClipboardSequenceNumber,
                IsClipboardFormatAvailable, OpenClipboard, RegisterClipboardFormatW,
            },
            Memory::{GlobalLock, GlobalSize, GlobalUnlock},
        },
    };

    pub struct Inspector;

    struct Open;
    impl Drop for Open {
        fn drop(&mut self) {
            unsafe {
                let _ = CloseClipboard();
            }
        }
    }

    impl Inspector {
        pub fn new() -> Result<Self, ()> {
            Ok(Self)
        }

        pub fn snapshot(&mut self) -> Result<Snapshot, ()> {
            unsafe {
                OpenClipboard(None).map_err(|_| ())?;
                let _open = Open;
                let generation = GetClipboardSequenceNumber();
                if generation == 0 {
                    return Err(());
                }
                let mut marked = false;
                for name in [
                    "ExcludeClipboardContentFromMonitorProcessing",
                    "Clipboard Viewer Ignore",
                    "CanIncludeInClipboardHistory",
                    "CanUploadToCloudClipboard",
                ] {
                    let wide: Vec<u16> = name.encode_utf16().chain(Some(0)).collect();
                    let format = RegisterClipboardFormatW(PCWSTR(wide.as_ptr()));
                    if format == 0 {
                        return Err(());
                    }
                    if IsClipboardFormatAvailable(format).is_err() {
                        continue;
                    }
                    if name == "ExcludeClipboardContentFromMonitorProcessing"
                        || name == "Clipboard Viewer Ignore"
                    {
                        marked = true;
                        continue;
                    }
                    let handle = GetClipboardData(format).map_err(|_| ())?;
                    let memory = windows::Win32::Foundation::HGLOBAL(handle.0);
                    if GlobalSize(memory) < 4 {
                        return Err(());
                    }
                    let ptr = GlobalLock(memory);
                    if ptr.is_null() {
                        return Err(());
                    }
                    let value = std::ptr::read_unaligned(ptr.cast::<u32>());
                    let _ = GlobalUnlock(memory);
                    marked |= super::history_flag(value)?;
                }
                if GetClipboardSequenceNumber() != generation {
                    return Err(());
                }
                Ok(Snapshot {
                    generation: u64::from(generation),
                    marked,
                })
            }
        }
    }
}

