#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn windows_flags_require_zero_for_exclusion_and_reject_invalid_values() {
        assert_eq!(history_flag(0), Ok(true));
        assert_eq!(history_flag(1), Ok(false));
        assert_eq!(history_flag(2), Err(()));
    }

    #[test]
    fn rejects_marker_changes_and_replaced_payloads() {
        let before = Snapshot {
            generation: 10,
            marked: false,
        };
        assert!(before.unchanged_and_public(before));
        assert!(!before.unchanged_and_public(Snapshot {
            generation: 11,
            marked: false
        }));
        assert!(!before.unchanged_and_public(Snapshot {
            generation: 10,
            marked: true
        }));
        assert!(!Snapshot {
            generation: 10,
            marked: true
        }
        .unchanged_and_public(before));
    }
}
